/**
 * F01 — every SMS that carries a credential must tell `sendSMS` so, otherwise
 * the redaction in lib/sms.ts never applies and the code lands in `sms_messages`.
 * See project-docs/DENEL_FRAMADA_AUDIT_2026-10-25.md (F01).
 *
 * Each sender is driven for real (the real OTP libraries and routes, against a
 * real database) with `sendSMS` captured, and what the sender hands it is read
 * back. An ordinary message is checked as a control, so "mark everything" cannot
 * pass.
 *
 * ── Safety ──────────────────────────────────────────────────────────────────
 * Routes open their own connection, so fixtures are COMMITTED. The suite refuses
 * anything but a LOCAL Postgres (like sms-sender-call-sites) and deletes what it
 * created. Codes are generated by the code under test and never printed.
 *
 *   cd backend && node scripts/dev-local.mjs vitest run tests/integration/sms-sensitive-call-sites.test.ts
 */

import { Hono } from 'hono'
import { afterAll, beforeAll, beforeEach, describe, expect, it, vi } from 'vitest'
import type { HonoEnv } from '../../src/lib/types'

const RAW_DB_URL = process.env.DATABASE_URL ?? ''
const IS_LOCAL = /@(localhost|127\.0\.0\.1|host\.docker\.internal)([:/]|$)/.test(RAW_DB_URL)
const skip = !IS_LOCAL

vi.mock('../../src/config/env', () => ({
  env: {
    DATABASE_URL: process.env.DATABASE_URL ?? 'postgresql://localhost:5433/framada',
    BETTER_AUTH_SECRET: 'test-secret-that-is-at-least-32-characters-!!',
    BETTER_AUTH_URL: 'http://localhost:3000',
    NODE_ENV: 'test',
  },
  validateBackendEnv: vi.fn(),
  isSelfHealEnabled: () => false,
  isDevEnvironment: () => false,
  resolvedEnvironment: () => 'production',
}))
vi.mock('../../src/lib/rbac')
vi.mock('../../src/lib/audit', () => ({
  createAuditLog: vi.fn(),
  recordDiffAudit: vi.fn(),
  computeChangedFields: vi.fn(() => ({})),
  redactForAudit: vi.fn((row: unknown) => row),
  auditMiddleware: () => async (_c: unknown, next: () => Promise<void>) => next(),
}))
vi.mock('../../src/lib/sms', () => ({
  sendSMS: vi.fn(async () => ({ success: true })),
}))
vi.mock('../../src/lib/logger', () => ({
  logError: vi.fn(),
  logger: { info: vi.fn(), error: vi.fn(), warn: vi.fn(), debug: vi.fn() },
}))
vi.mock('../../src/lib/google-calendar', () => ({
  enrichAppointment: vi.fn(async () => null),
  syncAppointmentCreated: vi.fn(async () => null),
  syncAppointmentDeleted: vi.fn(async () => null),
  syncAppointmentUpdated: vi.fn(async () => null),
}))

import { eq, inArray, sql } from 'drizzle-orm'
import { type DB, getDb } from '../../src/db'
import {
  appointments,
  doctors,
  patientOtpCodes,
  patients,
  specialists,
  staff,
  staffRegistrationInvites,
} from '../../src/db/schema'
import { requestOtp, requestOtpByPhone } from '../../src/lib/patient-otp'
import { checkPermission, getCurrentUser } from '../../src/lib/rbac'
import { sendSMS } from '../../src/lib/sms'
import { requestStaffOtp } from '../../src/lib/staff-otp'
import { appointmentWorkflowApp } from '../../src/routes/appointment-workflow'
import { appointmentsApp } from '../../src/routes/appointments'
import { staffRegistrationApp } from '../../src/routes/staff-registration'

const TAG = `sens-${Date.now()}`
const PATIENT_PHONE = '0240000071'
const OTP_BY_PHONE = '0240000072'
const STAFF_PHONE = '0240000073'
const REG_PHONE = '0240000074'

let db: DB
let app: Hono<HonoEnv>
let adminUserId: string
let patientId: string
let appointmentId: string
let staffId: string
const regToken = `reg-${TAG}`

const created = { doctors: [] as string[], specialists: [] as string[] }

/** The recipient objects `sendSMS` was handed for `phone`, newest last. */
function handedFor(phone: string) {
  return vi
    .mocked(sendSMS)
    .mock.calls.flatMap(([recipients]) => recipients)
    .filter((r) => r.phone === phone)
}

async function post(path: string, payload?: unknown) {
  const res = await app.request(path, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: payload === undefined ? undefined : JSON.stringify(payload),
  })
  let body: unknown = null
  try {
    body = await res.json()
  } catch {
    /* empty body */
  }
  return { status: res.status, body }
}

describe.skipIf(skip)('F01 — every credential-bearing SMS is marked for redaction', () => {
  beforeAll(async () => {
    db = getDb(RAW_DB_URL)
    vi.stubEnv('BETTER_AUTH_SECRET', 'test-secret-that-is-at-least-32-characters-!!')
    // The confirmation link is a page of the portal; a deployed backend always states where it is.
    vi.stubEnv('PORTAL_URL', 'https://portal.example.test')

    const users = await db.execute<{ id: string }>(
      sql`SELECT id FROM "user" ORDER BY "createdAt" LIMIT 1`
    )
    adminUserId = users.rows[0]?.id
    if (!adminUserId) throw new Error('No rows in "user" — run `pnpm --filter backend seed:admin`')

    const [p] = await db
      .insert(patients)
      .values({
        name: `IT Sens ${TAG}`,
        dob: new Date('1990-01-01'),
        gender: 'other',
        phone: PATIENT_PHONE,
      })
      .returning({ id: patients.id })
    patientId = p.id

    const [s] = await db
      .insert(staff)
      .values({
        staffId: `IT-${TAG}`,
        fullName: `IT Sens Staff ${TAG}`,
        employmentType: 'permanent',
        phone: STAFF_PHONE,
      })
      .returning({ id: staff.id })
    staffId = s.id

    await db.insert(staffRegistrationInvites).values({
      token: regToken,
      expiresAt: new Date(Date.now() + 60 * 60 * 1000),
    })

    const [spec] = await db
      .insert(specialists)
      .values({ name: `IT Sens Spec ${TAG}`, defaultCommissionRate: 0, withholdingTaxRate: 0 })
      .returning({ id: specialists.id })
    created.specialists.push(spec.id)
    const [doc] = await db
      .insert(doctors)
      .values({ specialistId: spec.id, specialty: 'General Dentistry' })
      .returning({ id: doctors.id })
    created.doctors.push(doc.id)
    const [a] = await db
      .insert(appointments)
      .values({
        patientId,
        doctorId: doc.id,
        date: new Date(Date.now() + 3 * 24 * 60 * 60 * 1000),
        status: 'scheduled',
        type: 'consultation',
      })
      .returning({ id: appointments.id })
    appointmentId = a.id

    app = new Hono<HonoEnv>()
    app.route('/api/appointment-workflow', appointmentWorkflowApp)
    app.route('/api/appointments', appointmentsApp)
    app.route('/api/staff-registration', staffRegistrationApp)
  })

  afterAll(async () => {
    vi.unstubAllEnvs()
    if (skip || !db) return
    await db.delete(patientOtpCodes).where(eq(patientOtpCodes.phone, OTP_BY_PHONE))
    await db.delete(appointments).where(eq(appointments.id, appointmentId))
    await db.delete(patients).where(eq(patients.id, patientId))
    await db.delete(staff).where(eq(staff.id, staffId))
    await db.delete(staffRegistrationInvites).where(eq(staffRegistrationInvites.token, regToken))
    if (created.doctors.length) await db.delete(doctors).where(inArray(doctors.id, created.doctors))
    if (created.specialists.length)
      await db.delete(specialists).where(inArray(specialists.id, created.specialists))
  })

  beforeEach(() => {
    vi.clearAllMocks()
    vi.mocked(getCurrentUser).mockResolvedValue({
      id: adminUserId,
      email: 'admin@deneldental.com',
      name: 'Admin',
      role: 'admin',
      roleId: 'admin',
    } as never)
    vi.mocked(checkPermission).mockResolvedValue(true)
  })

  it('patient login OTP (by patient id) is sensitive', async () => {
    const res = await requestOtp(db, patientId, 'login_phone', PATIENT_PHONE)
    expect(res.ok).toBe(true)
    const [r] = handedFor(PATIENT_PHONE)
    expect(r.message).toMatch(/\b\d{6}\b/) // the recipient is still sent the real code
    expect(r.sensitive).toBe(true)
  })

  it('patient login OTP (by phone) is sensitive', async () => {
    const res = await requestOtpByPhone(db, OTP_BY_PHONE, 'login_phone')
    expect(res.ok).toBe(true)
    const [r] = handedFor(OTP_BY_PHONE)
    expect(r.message).toMatch(/\b\d{6}\b/)
    expect(r.sensitive).toBe(true)
  })

  it.each([
    'login_phone',
    'password_reset',
  ] as const)('staff %s OTP is sensitive', async (purpose) => {
    const res = await requestStaffOtp(db, staffId, purpose, STAFF_PHONE)
    expect(res.ok).toBe(true)
    // The send is detached on purpose (timing oracle), so wait for it.
    await vi.waitFor(() => expect(handedFor(STAFF_PHONE).length).toBeGreaterThan(0))
    const r = handedFor(STAFF_PHONE).at(-1)
    expect(r?.message).toMatch(/\b\d{6}\b/)
    expect(r?.sensitive).toBe(true)
  })

  it('staff registration OTP is sensitive', async () => {
    const { status, body } = await post(`/api/staff-registration/public/${regToken}/send-otp`, {
      phone: REG_PHONE,
    })
    expect(status, JSON.stringify(body)).toBe(200)
    const sent = vi.mocked(sendSMS).mock.calls.flatMap(([recipients]) => recipients)
    const r = sent.find((x) => /registration code/.test(x.message))
    expect(r, 'registration SMS was not sent').toBeDefined()
    expect(r?.message).toMatch(/\b\d{6}\b/)
    expect(r?.sensitive).toBe(true)
  })

  it('appointment confirmation link: real link is sent, the stored copy has no token', async () => {
    const { status, body } = await post(
      `/api/appointment-workflow/${appointmentId}/send-confirmation`
    )
    expect(status, JSON.stringify(body)).toBe(200)

    const [r] = handedFor(PATIENT_PHONE)
    const [row] = await db
      .select({ token: appointments.confirmationToken })
      .from(appointments)
      .where(eq(appointments.id, appointmentId))
    expect(row.token).toBeTruthy()
    // What the patient receives still contains the working link…
    expect(r.message).toContain(`https://portal.example.test/c/${row.token}`)
    // …and what Denel keeps does not, but is otherwise the same message.
    expect(r.storedMessage).toBeDefined()
    expect(r.storedMessage).not.toContain(row.token as string)
    expect(r.storedMessage).toContain('/c/[token redacted]')
    expect(r.storedMessage).toContain(`IT Sens ${TAG}`)
  })

  it('control: an ordinary appointment update SMS is not marked or rewritten', async () => {
    const res = await app.request(`/api/appointments/${appointmentId}`, {
      method: 'PATCH',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ data: { status: 'confirmed' }, sendSMS: true }),
    })
    const status = res.status
    const body = await res.json().catch(() => null)
    expect(status, JSON.stringify(body)).toBe(200)

    const [r] = handedFor(PATIENT_PHONE)
    expect(r).toBeDefined()
    expect(r.sensitive).toBeUndefined()
    expect(r.storedMessage).toBeUndefined()
  })
})
