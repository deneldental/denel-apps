/**
 * F22 / D9 — who may upload what, and where it lands. See
 * project-docs/DENEL_FRAMADA_AUDIT_2026-10-25.md (§8.12).
 *
 * `POST /api/upload` checked only that someone was signed in. The caller chose the storage
 * category, the folder, the sub-folder and the file name, so a Team-app user could write into
 * patient-record storage, a repeated name replaced an object that already existed (a plain
 * PutObject overwrites), and `POST /api/upload/expense` named its object after the category and
 * the day, so two receipts for the same category on the same day overwrote each other.
 *
 * Now each upload names a kind of file the clinic stores. The kind fixes the storage category,
 * the apps and permissions that may use it and the validation profiles, and the file name is
 * generated by the server. These tests sign in as the real roles and drive the real app; only
 * the object store is faked, so every refusal is the real permission engine and the real
 * interface-scope guard speaking.
 *
 * ── Safety ── commits fixtures (logins and one staff record per Team-app user); local
 * Postgres only; everything is removed in afterAll.
 *
 *   cd backend && node scripts/dev-local.mjs vitest run tests/integration/upload-access.test.ts
 */
